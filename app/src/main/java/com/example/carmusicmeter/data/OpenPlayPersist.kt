package com.example.carmusicmeter.data

/**
 * Нужно ли перезаписать сохранённое открытое прослушивание после пачки событий.
 *
 * Пишем после начала и после окончания. Начало и контрольная точка сохраняют
 * состояние для восстановления, окончание — стирает его: иначе закрытое из-за
 * долгого сна прослушивание осталось бы в настройках, и следующая служба
 * закрыла бы его второй раз, удвоив прослушанное время.
 *
 * Остальные события (громкость, источники) состояние не меняют: их пачки
 * настройки не трогают, чтобы не писать на диск лишний раз.
 */
fun shouldPersistOpenPlay(events: List<LogEvent>, checkpoint: LogEvent?): Boolean =
    checkpoint != null || events.any { it.type == "track_started" || it.type == "track_ended" }
