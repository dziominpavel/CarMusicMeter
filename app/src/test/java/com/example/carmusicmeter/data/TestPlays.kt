package com.example.carmusicmeter.data

fun playRecord(
    playId: String = "p1",
    origin: String = "live",
    bootId: String = "b1",
    trackKey: String = "com.p::track::artist",
    title: String = "Track",
    artist: String = "Artist",
    startedAt: Long = 1_000L,
    endedAt: Long = 2_000L,
    endReason: String = "skipped",
    playedMs: Long = 900L,
    durationMs: Long = 180_000L,
    endPositionMs: Long? = playedMs,
    restored: Boolean = false,
    clockVerified: Boolean = true,
    open: Boolean = false,
): PlayRecord = PlayRecord(
    playId = playId,
    origin = origin,
    bootId = bootId,
    trackKey = trackKey,
    packageName = "com.p",
    source = "media_session",
    title = title,
    artist = artist,
    album = "Album",
    mediaId = "/music/track.flac",
    durationMs = durationMs,
    startedAt = startedAt,
    endedAt = endedAt,
    playedMs = playedMs,
    rawPlayedMs = playedMs,
    endPositionMs = endPositionMs,
    endReason = endReason,
    completed = endReason == "completed",
    restored = restored,
    clockVerified = clockVerified,
    volumeStart = 10,
    volumeEnd = 12,
    volumeLow = 10,
    volumeHigh = 12,
    volumeMax = 43,
    volumeSource = "mcu",
    volumeChanges = 1,
    volumeStats = mapOf(
        "mcu" to PlayVolume(
            start = 10,
            low = 10,
            high = 12,
            end = 12,
            max = 43,
            changes = 1,
            up = 2,
            down = 0,
            level = 11,
            raiseMs = 500L,
        ),
    ),
    seekBack = 0,
    seekForward = 0,
    deviceId = "dev",
    appVersion = "1.0",
    open = open,
)

fun endedEvent(
    playId: String = "p1",
    trackKey: String = "com.p::track::artist",
    startedAt: Long = 1_000L,
    endedAt: Long = 2_000L,
    playedMs: Long = 900L,
    endReason: String = "skipped",
    restored: Boolean = false,
): LogEvent = LogEvent(
    ts = endedAt,
    type = "track_ended",
    fields = linkedMapOf(
        "trackKey" to trackKey,
        "playId" to playId,
        "package" to "com.p",
        "source" to "media_session",
        "title" to "Track",
        "artist" to "Artist",
        "album" to "Album",
        "mediaId" to "/music/track.flac",
        "durationMs" to 180_000L,
        "playedMs" to playedMs,
        "rawPlayedMs" to playedMs,
        "endPositionMs" to playedMs,
        "endReason" to endReason,
        "completed" to (endReason == "completed"),
        "startedAt" to startedAt,
        "volumeStart" to 10,
        "volumeEnd" to 12,
        "volumeLow" to 10,
        "volumeHigh" to 12,
        "volumeChanges" to 1,
        "volumeMax" to 43,
        "volumeSource" to "mcu",
        "volumeStats" to mapOf(
            "mcu" to mapOf(
                "start" to 10,
                "low" to 10,
                "high" to 12,
                "end" to 12,
                "max" to 43,
                "changes" to 1,
            ),
        ),
        "seekBack" to 1,
        "seekForward" to 2,
    ).apply {
        if (restored) put("restored", true)
    },
)
